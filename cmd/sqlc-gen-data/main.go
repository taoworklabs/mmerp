// Command sqlc-gen-data is a sqlc process plugin (format json) that emits one
// data engine descriptor per query into each module's store package.
package main

import (
	"encoding/json"
	"fmt"
	"go/format"
	"io"
	"os"
	"path/filepath"
	"strings"
	"unicode"
)

// request holds the only GenerateRequest fields the plugin reads; sqlc sends
// protojson with proto field names.
type request struct {
	Settings struct {
		Queries []string `json:"queries"`
	} `json:"settings"`
	Queries []struct {
		Name     string            `json:"name"`
		Cmd      string            `json:"cmd"`
		Params   []json.RawMessage `json:"params"`
		Comments []string          `json:"comments"`
		Columns  []struct {
			Name string `json:"name"`
		} `json:"columns"`
	} `json:"queries"`
}

var kinds = map[string]string{":one": "One", ":many": "Many", ":exec": "Exec", ":execrows": "ExecRows"}

func generate(in []byte) ([]byte, error) {
	var req request
	if err := json.Unmarshal(in, &req); err != nil {
		return nil, err
	}
	if len(req.Settings.Queries) == 0 {
		return nil, fmt.Errorf("no queries path in settings")
	}
	// internal/modules/hrm/queries.sql -> hrm
	module := filepath.Base(filepath.Dir(req.Settings.Queries[0]))

	var b strings.Builder
	b.WriteString("// Code generated by sqlc-gen-data. DO NOT EDIT.\n\npackage store\n\n")
	b.WriteString("import (\n\"github.com/taoworklabs/mmerp/internal/platform\"\n\"github.com/taoworklabs/mmerp/internal/platform/data\"\n)\n\n")
	b.WriteString("func newQ(c platform.Conn) *Queries { return New(c) }\n\n")
	for _, q := range req.Queries {
		name := module + "." + q.Name
		if isBase(q.Comments) {
			if len(q.Params) > 0 {
				return nil, fmt.Errorf("%s: a data:base query takes no parameters", name)
			}
			cols := make([]string, len(q.Columns))
			for i, c := range q.Columns {
				cols[i] = fmt.Sprintf("%q", c.Name)
			}
			fmt.Fprintf(&b, "var %s = data.NewBase(%q, %s, []string{%s}, (*Queries).%s)\n",
				q.Name, name, lowerFirst(q.Name), strings.Join(cols, ", "), q.Name)
			continue
		}
		kind, ok := kinds[q.Cmd]
		if !ok {
			return nil, fmt.Errorf("%s: unsupported cmd %s", name, q.Cmd)
		}
		arity := 0
		if len(q.Params) > 0 {
			arity = 1 // sqlc-go folds several parameters into one Params struct
		}
		fmt.Fprintf(&b, "var %s = data.%s%d(%q, newQ, (*Queries).%s)\n", q.Name, kind, arity, name, q.Name)
	}
	return format.Source([]byte(b.String()))
}

// isBase reports whether the query carries the "-- data:base" marker; sqlc
// passes comment lines with "--" stripped.
func isBase(comments []string) bool {
	for _, c := range comments {
		if strings.TrimSpace(c) == "data:base" {
			return true
		}
	}
	return false
}

// lowerFirst matches the name sqlc gives a query's SQL constant.
func lowerFirst(s string) string {
	r := []rune(s)
	r[0] = unicode.ToLower(r[0])
	return string(r)
}

func main() {
	in, err := io.ReadAll(os.Stdin)
	if err == nil {
		var out []byte
		if out, err = generate(in); err == nil {
			// []byte marshals to base64, which protojson expects for bytes fields.
			err = json.NewEncoder(os.Stdout).Encode(map[string]any{
				"files": []map[string]any{{"name": "data.gen.go", "contents": out}},
			})
		}
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "sqlc-gen-data:", err)
		os.Exit(1)
	}
}
